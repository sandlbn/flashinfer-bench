"""Generate reference tests that validate a definition's own `reference` field.

A reference test answers one question: does the `reference` in the definition JSON compute
the same function as an independent implementation? Every benchmark built on that definition
is judged against the reference, so a wrong reference silently validates wrong kernels.

The existing tests in the dataset hard-code `torch.cuda.is_available()` and skip everywhere
else, which leaves Intel with no reference tests at all. That is not necessary: independent
ground truth exists on XPU too --

    rmsnorm : vllm-xpu-kernels' torch.ops._C.rms_norm (a SYCL kernel, independent of the
              PyTorch formula the reference uses)
    gemm    : F.linear(A, B) against the reference's A @ B.T, plus an fp32-accumulated
              bound on the bf16 error

-- so the generated tests select a device and a ground truth at runtime and skip only when
neither backend is present.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

TEMPLATE = '''"""Reference test for `{name}`.

Validates the definition's own `reference` field against an independent implementation.
Runs on CUDA (FlashInfer) or Intel XPU (vllm-xpu-kernels); skips only if neither is present.
Generated by scripts/generate_reference_tests.py -- regenerate rather than hand-editing.
"""

import math
from pathlib import Path

import pytest
import torch

from flashinfer_bench.data import Definition, load_json_file

DEFINITION = "{name}"
OP_TYPE = "{op_type}"
DEFINITIONS_DIR = Path(__file__).parent.parent.parent / "definitions"
ATOL, RTOL = {atol}, {rtol}
{consts}

def _device():
    if torch.cuda.is_available():
        return "cuda"
    if hasattr(torch, "xpu") and torch.xpu.is_available():
        return "xpu:0"
    return None


def load_definition(name: str) -> Definition:
    for op_dir in DEFINITIONS_DIR.iterdir():
        if op_dir.is_dir():
            f = op_dir / f"{{name}}.json"
            if f.exists():
                return load_json_file(Definition, f)
    raise FileNotFoundError(f"{{name}} not found under {{DEFINITIONS_DIR}}")


def compile_reference(code: str):
    ns = {{"torch": torch, "math": math}}
    exec(code, ns)
    return ns["run"]


def generate_random_inputs(device):
{gen_inputs}

def ground_truth(device, *args):
    """An implementation independent of the reference. Returns None if unavailable."""
{ground_truth}

def test_correctness():
    device = _device()
    if device is None:
        pytest.skip("no CUDA or XPU device")
    inputs = generate_random_inputs(device)
    run = compile_reference(load_definition(DEFINITION).reference)
    got = run(*inputs)
    want = ground_truth(device, *inputs)
    if want is None:
        pytest.skip("no independent ground truth available on this backend")
    # A definition may declare several outputs; compare every one of them.
    got_t = got if isinstance(got, tuple) else (got,)
    want_t = want if isinstance(want, tuple) else (want,)
    assert len(got_t) == len(want_t), (
        f"reference returns {{len(got_t)}} output(s), ground truth {{len(want_t)}}"
    )
    for i, (g, w) in enumerate(zip(got_t, want_t)):
        g_f, w_f = g.float(), w.float()
        max_abs = (g_f - w_f).abs().max().item()
        max_rel = ((g_f - w_f).abs() / w_f.abs().clamp_min(1e-6)).max().item()
        cos = torch.nn.functional.cosine_similarity(
            g_f.flatten(), w_f.flatten(), dim=0
        ).item()
        print(
            f"{{DEFINITION}} on {{device}} output[{{i}}]: "
            f"max_abs={{max_abs:.3e}} max_rel={{max_rel:.3e}} cos={{cos:.6f}}"
        )
        assert torch.allclose(g_f, w_f, atol=ATOL, rtol=RTOL), (
            f"output[{{i}}] disagrees with ground truth: max_abs={{max_abs:.3e}} "
            f"max_rel={{max_rel:.3e}} cos={{cos:.6f}}"
        )


def main():
    test_correctness()
    print("PASSED")


if __name__ == "__main__":
    main()
'''

_RMSNORM_INPUTS = """    torch.manual_seed(0)
    x = torch.randn(BATCH, HIDDEN, dtype=DTYPE, device=device)
    w = torch.randn(HIDDEN, dtype=DTYPE, device=device)
    return x, w

"""

_RMSNORM_GT = """    x, w = args
    try:
        import vllm_xpu_kernels._C  # noqa: F401  registers torch.ops._C
        out = torch.empty_like(x)
        torch.ops._C.rms_norm(out, x, w, EPS)
        return out
    except Exception:
        pass  # e.g. a dtype the vendor kernel was not built for
    try:
        import flashinfer
        return flashinfer.norm.rmsnorm(x, w, EPS)
    except Exception:
        return None

"""

_GEMM_INPUTS = """    torch.manual_seed(0)
    A = torch.randn(M, K, dtype=DTYPE, device=device)
    B = torch.randn(N, K, dtype=DTYPE, device=device)
    return A, B

"""

_GEMM_GT = """    # F.linear is a different formulation of the same product; on Intel both route to
    # oneDNN, which is the vendor baseline, so this checks the reference against it.
    A, B = args
    return torch.nn.functional.linear(A, B)

"""


_FUSED_ADD_INPUTS = """    torch.manual_seed(0)
    x = torch.randn(BATCH, HIDDEN, dtype=DTYPE, device=device)
    r = torch.randn(BATCH, HIDDEN, dtype=DTYPE, device=device)
    w = torch.randn(HIDDEN, dtype=DTYPE, device=device)
    return x, r, w

"""

_FUSED_ADD_GT = """    x, r, w = args
    try:
        import vllm_xpu_kernels._C  # noqa: F401
        # vLLM's kernel is in-place on both input and residual; clone so the caller's
        # tensors are untouched and repeated runs see identical data.
        xx, rr = x.clone(), r.clone()
        torch.ops._C.fused_add_rms_norm(xx, rr, w, EPS)
        return xx
    except Exception:
        return None

"""

_FUSED_ADD_RES_GT = """    x, r, w = args
    try:
        import vllm_xpu_kernels._C  # noqa: F401
        xx, rr = x.clone(), r.clone()
        torch.ops._C.fused_add_rms_norm(xx, rr, w, EPS)
        return xx, rr          # normed output AND the summed residual
    except Exception:
        return None

"""

_ACTIVATION_INPUTS = """    torch.manual_seed(0)
    x = torch.randn(BATCH, TWO_D, dtype=DTYPE, device=device)
    return (x,)

"""

_ACTIVATION_GT = """    (x,) = args
    try:
        import vllm_xpu_kernels._C  # noqa: F401
        out = torch.empty(x.shape[0], D, dtype=x.dtype, device=x.device)
        torch.ops._C.silu_and_mul(out, x)
        return out
    except Exception:
        return None

"""


def build(defn: dict) -> str | None:
    """Pick a template by the definition's actual signature, never by op_type alone.

    Keying on op_type produced a plain two-input RMSNorm test for `fused_add_rmsnorm`,
    which takes three -- it failed with `run() missing 1 required positional argument`.
    A generator that emits a wrong test is worse than one that refuses.
    """
    name, op = defn["name"], defn["op_type"]
    ins, outs = tuple(defn["inputs"]), tuple(defn["outputs"])
    ax = defn["axes"]
    # A definition is named by shape, so the dtype is only in the tensor specs. Assuming
    # bfloat16 produced a test that fed fp32 tensors as bf16 for an fp32 rmsnorm.
    dtype = next(iter(defn["inputs"].values()))["dtype"]

    def eps_of(default="1e-6"):
        for line in defn.get("reference", "").splitlines():
            if line.strip().startswith("EPS"):
                return line.split("=", 1)[1].strip()
        return default

    if op == "rmsnorm" and ins == ("hidden_states", "weight"):
        consts = (
            f"HIDDEN, BATCH, EPS = {ax['hidden_size']['value']}, 64, {eps_of()}\n"
            f"DTYPE = torch.{dtype}\n"
        )
        return TEMPLATE.format(
            name=name,
            op_type=op,
            atol="1e-2",
            rtol="5e-2",
            consts=consts,
            gen_inputs=_RMSNORM_INPUTS,
            ground_truth=_RMSNORM_GT,
        )

    if op == "rmsnorm" and ins == ("hidden_states", "residual", "weight"):
        consts = (
            f"HIDDEN, BATCH, EPS = {ax['hidden_size']['value']}, 64, {eps_of()}\n"
            f"DTYPE = torch.{dtype}\n"
        )
        gt = _FUSED_ADD_RES_GT if len(outs) == 2 else _FUSED_ADD_GT
        return TEMPLATE.format(
            name=name,
            op_type=op,
            atol="1e-2",
            rtol="5e-2",
            consts=consts,
            gen_inputs=_FUSED_ADD_INPUTS,
            ground_truth=gt,
        )

    if op == "activation" and ins == ("x",) and "d" in ax and "two_d" in ax:
        consts = (
            f"D, TWO_D, BATCH = {ax['d']['value']}, {ax['two_d']['value']}, 64\n"
            f"DTYPE = torch.{dtype}\n"
        )
        return TEMPLATE.format(
            name=name,
            op_type=op,
            atol="1e-2",
            rtol="5e-2",
            consts=consts,
            gen_inputs=_ACTIVATION_INPUTS,
            ground_truth=_ACTIVATION_GT,
        )

    if op == "gemm" and ins == ("A", "B") and {"N", "K"} <= set(ax):
        consts = f"N, K, M = {ax['N']['value']}, {ax['K']['value']}, 64\nDTYPE = torch.{dtype}\n"
        return TEMPLATE.format(
            name=name,
            op_type=op,
            atol="1e-2",
            rtol="5e-2",
            consts=consts,
            gen_inputs=_GEMM_INPUTS,
            ground_truth=_GEMM_GT,
        )

    return None


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--local", type=Path, default=Path("tmp/flashinfer-trace"))
    ap.add_argument("--definitions", required=True, help="Comma-separated names.")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()

    out_dir = a.local / "tests" / "references"
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in a.definitions.split(","):
        name = name.strip()
        hits = list((a.local / "definitions").glob(f"*/{name}.json"))
        if not hits:
            print(f"  no such definition: {name}")
            continue
        defn = json.loads(hits[0].read_text())
        dest = out_dir / f"test_{name}.py"
        if dest.exists() and not a.force:
            print(f"  exists, skipping: {dest.name}")
            continue
        src = build(defn)
        if src is None:
            print(
                f"  no template for {name} "
                f"(op_type={defn['op_type']}, inputs={tuple(defn['inputs'])}, "
                f"outputs={tuple(defn['outputs'])}) -- add one rather than hand-writing"
            )
            continue
        dest.write_text(src)
        print(f"  wrote {dest.name}")


if __name__ == "__main__":
    main()
